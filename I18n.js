// Best supported locale from a list of BCP-47 tags (e.g. Qt.uiLanguages()),
// matched on the primary language subtag. Falls back to "en".
function resolveLocale(uiLanguages, supported) {
    var list = supported || Locales
    if (!Array.isArray(uiLanguages)) return "en"
    for (var i = 0; i < uiLanguages.length; i++) {
        var tag = String(uiLanguages[i] || "").toLowerCase()
        var primary = tag.split(/[-_]/)[0]
        if (list.indexOf(primary) !== -1) return primary
    }
    return "en"
}

// {placeholder} interpolation only — not a full ICU MessageFormat.
// ponytail: no CLDR plural-category support (each caller picks a one/other
// key itself, e.g. statusStory vs statusStories); upgrade to a real
// MessageFormat/plural-rules library if a locale needs proper plural forms.
function interpolate(str, vars) {
    if (!vars) return str
    return String(str).replace(/\{(\w+)\}/g, function(m, k) {
        return vars[k] !== undefined ? String(vars[k]) : m
    })
}

function t(locale, key, vars) {
    var table = strings[locale] || strings.en
    var s = table[key]
    if (s === undefined) s = (strings.en[key] !== undefined) ? strings.en[key] : key
    return interpolate(s, vars)
}
